// Offline, deterministic compilation of the reviewed TSV. No network or dependencies.
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';

export const sharedQuestions={
 educator:['Was this person an educator?','ব্যক্তিটি কি শিক্ষাবিদ ছিলেন?'],
 comic:['Is this character from a comic strip?','চরিত্রটি কি কমিক স্ট্রিপ থেকে এসেছে?'],
 science_tool:['Is it an instrument used for scientific observation?','এটি কি বৈজ্ঞানিক পর্যবেক্ষণের যন্ত্র?'],
 politician:['Was this person a political leader?','ব্যক্তিটি কি রাজনৈতিক নেতা ছিলেন?'],
 military:['Did this person serve in the military?','ব্যক্তিটি কি সামরিক বাহিনীতে কাজ করেছেন?'],
 revolutionary:['Was this person involved in the anti-colonial revolutionary movement?','ব্যক্তিটি কি ঔপনিবেশিক শাসনের বিরুদ্ধে বিপ্লবী আন্দোলনে যুক্ত ছিলেন?'],
 composer:['Is this person a music composer?','ব্যক্তিটি কি সংগীত পরিচালক?'],
 wicketkeeper:['Has this cricketer played as a wicketkeeper?','ক্রিকেটার কি উইকেটকিপার হিসেবে খেলেছেন?'],
 economist:['Is this person an economist?','ব্যক্তিটি কি অর্থনীতিবিদ?'],
 reporter:['Is this character a reporter?','চরিত্রটি কি সাংবাদিক?'],
 amphibian:['Is it an amphibian?','এটি কি উভচর প্রাণী?'],
 crustacean:['Is it a crustacean?','এটি কি ক্রাস্টেশিয়ান জাতীয় প্রাণী?'],
 textile:['Is it made from or used to work with cloth?','এটি কি কাপড়ের তৈরি অথবা কাপড়ের কাজে লাগে?'],
 instrument:['Is it a musical instrument?','এটি কি বাদ্যযন্ত্র?'],
 percussion:['Is it a percussion instrument played by striking?','এটি কি আঘাত করে বাজানো তালবাদ্য?'],
 board_game:['Is it a board used for a tabletop game?','এটি কি টেবিলে খেলার বোর্ড?']
};

export function compileCurated(text){
 const entries=[],questions=Object.fromEntries(Object.entries(sharedQuestions).map(([k,v])=>[k,v[0]]));
 const bangla=Object.fromEntries(Object.entries(sharedQuestions).map(([k,v])=>[k,v[1]]));
 const ids=new Set(),names=new Set();
 for(const line of text.split(/\r?\n/).filter(l=>l.trim()&&!l.startsWith('#'))){
  const fields=line.split('|');
  assert.ok(fields.length===8||fields.length===9,'Expected eight fields and an optional review date: '+line);
  const [id,name,category,tags,en,bn,article,locator,checkedOn='2026-11-04']=fields;
  assert.match(checkedOn,/^\d{4}-\d{2}-\d{2}$/);
  assert.match(id,/^[a-z0-9]+(?:-[a-z0-9]+)*$/);
  assert.ok(!ids.has(id),'Duplicate id: '+id);ids.add(id);
  const normalizedName=name.toLowerCase().normalize('NFKC');
  assert.ok(!names.has(normalizedName),'Duplicate name: '+name);names.add(normalizedName);
  assert.ok(['characters','animals','objects'].includes(category));
  assert.ok(en.endsWith('?')&&bn.endsWith('?')&&locator.trim());
  const facts={};
  for(const tag of tags.split(',')){
   const key=tag.replace(/^!/,''),value=!tag.startsWith('!');
   assert.ok(!Object.hasOwn(facts,key),'Repeated fact: '+id+'/'+key);
   facts[key]=value;
  }
  const diagnostic='cue_'+id.replaceAll('-','_');
  facts[diagnostic]=true;questions[diagnostic]=en;bangla[diagnostic]=bn;
  const url=article.startsWith('https://')?article:'https://en.wikipedia.org/wiki/'+article;
  entries.push({id,name,category,facts,diagnostic,sources:[{url,locator,checkedOn}]});
 }
 return {entries,questions,bangla};
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
 const data=compileCurated(await readFile(new URL('./curated-batch.tsv',import.meta.url),'utf8'));
 const header='// Generated by build-curated.mjs from reviewed curated-batch.tsv. Do not hand edit.\n';
 const outputs={
  'knowledge.generated.js':header+'export const generatedEntries='+JSON.stringify(data.entries,null,2)+';\n',
  'knowledge.questions.generated.js':header+'export const generatedQuestions='+JSON.stringify(data.questions,null,2)+';\nexport const generatedBanglaQuestions='+JSON.stringify(data.bangla,null,2)+';\n'
 };
 for(const [name,content] of Object.entries(outputs)){
  const url=new URL('./'+name,import.meta.url);
  if(process.argv.includes('--check'))assert.equal(await readFile(url,'utf8'),content,'Stale generated file: '+name);
  else await writeFile(url,content);
 }
 console.log('Reviewed batch:',data.entries.length, 'entries; diagnostic questions:',data.entries.length);
}
