export function guessFont(lang, name) {
  const bangla = lang === "bn" || /[\u0980-\u09FF]/.test(name || "");
  return bangla
    ? '400 28px SolaimanLipi, "Times New Roman", Times, serif'
    : '500 34px Caveat, "Segoe Script", cursive';
}
