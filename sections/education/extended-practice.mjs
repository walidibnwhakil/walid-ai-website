/* Deterministic, mathematically checkable practice variations: every stem
   uses an encoded operand, so a level can rotate thousands of validated tasks.
   They are explicitly worked-practice variants, not thousands of textbook chapters. */
function arithmetic(subject,level,kind,index){
  const base=18+index*2+Number(level==="admission"?12:level==="bcs"?10:level)*4;
  const b=3+(index%17),c=2+(index%9);
  let q,correct,why;
  switch(kind){
    case "arithmetic":
      q="("+base+" + "+b+") × "+c+" = কত?";
      correct=(base+b)*c;
      why="প্রথমে বন্ধনীর যোগ: "+(base+b)+"; তারপর "+c+" দিয়ে গুণ করে "+correct+"।";
      break;
    case "algebra":
      q=(c+"x + "+b+" = "+(base*c+b)+" হলে x কত?");
      correct=base;
      why="প্রথমে "+b+" বিয়োগ করে "+(base*c)+"; তারপর "+c+" দিয়ে ভাগ করে x="+base+"।";
      break;
    case "percent":
      q=""+base*10+" টাকার "+c*5+"% কত টাকা?";
      correct=base*c/2;
      why=base*10+" × "+(c*5)+"/১০০ = "+correct+" টাকা।";
      break;
    case "ratio":
      q="একটি পরিমাণকে "+b+":"+c+" অনুপাতে ভাগ করলে মোট "+((b+c)*base)+"-এর প্রথম অংশ কত?";
      correct=b*base;
      why="প্রথম অংশ = "+((b+c)*base)+" × "+b+"/"+(b+c)+" = "+correct+"।";
      break;
    case "average":
      q=base+", "+(base+b)+", "+(base+2*b)+"-এর গড় কত?";
      correct=base+b;
      why="তিনটির যোগফল "+(3*(base+b))+"; ৩ দিয়ে ভাগ করলে "+correct+"।";
      break;
    case "geometry":
      q="দৈর্ঘ্য "+base+" মি ও প্রস্থ "+b+" মি আয়তক্ষেত্রের পরিসীমা কত মিটার?";
      correct=2*(base+b);
      why="পরিসীমা ২×(দৈর্ঘ্য+প্রস্থ) = ২×"+(base+b)+" = "+correct+" মি।";
      break;
    case "equation":
      q="x/2 + "+b+" = "+(base+b)+" হলে x কত?";
      correct=2*base;
      why="উভয় পাশ থেকে "+b+" বিয়োগ করলে x/2="+base+"; তাই x="+correct+"।";
      break;
    case "square":
      q="বাহু "+base+" মিটার হলে বর্গক্ষেত্রের ক্ষেত্রফল কত বর্গমিটার?";
      correct=base*base;
      why="ক্ষেত্রফল = বাহু² = "+base+"×"+base+" = "+correct+"।";
      break;
    case "sequence":
      q=base+", "+(base+b)+", "+(base+2*b)+", "+(base+3*b)+", … ধারার পরের পদ কী?";
      correct=base+4*b;
      why="প্রতি ধাপে "+b+" যোগ হচ্ছে; পরের পদ "+correct+"।";
      break;
    case "force":
      q="ভর "+base+" kg ও ত্বরণ "+b+" m/s² হলে লব্ধি বল কত N?";
      correct=base*b;
      why="নিউটনের দ্বিতীয় সূত্র: F=ma="+base+"×"+b+"="+correct+" N।";
      break;
    case "power":
      q="একটি যন্ত্রে বিভব পার্থক্য "+base+" V এবং প্রবাহ "+b+" A হলে ক্ষমতা কত ওয়াট?";
      correct=base*b;
      why="P=VI = "+base+"×"+b+" = "+correct+" ওয়াট।";
      break;
    case "interest":
      q=base*100+" টাকা মূলধনে বার্ষিক "+b+"% হারে ২ বছরের সরল সুদ কত টাকা?";
      correct=base*2*b;
      why="সরল সুদ = P×R×T/১০০ = "+(base*100)+"×"+b+"×২/১০০ = "+correct+"।";
      break;
    case "accounting":
      q="একটি প্রতিষ্ঠানের সম্পদ "+base*1000+" টাকা ও দায় "+b*1000+" টাকা হলে মালিকানা স্বত্ব কত টাকা?";
      correct=(base-b)*1000;
      why="মালিকানা স্বত্ব = সম্পদ − দায় = "+correct+" টাকা।";
      break;
    case "profit":
      q="পণ্যের ক্রয়মূল্য "+base*100+" টাকা এবং বিক্রয়মূল্য "+(base+c)*100+" টাকা হলে লাভ কত টাকা?";
      correct=c*100;
      why="লাভ = বিক্রয়মূল্য − ক্রয়মূল্য = "+correct+" টাকা।";
      break;
    case "cost":
      q="একটি দোকানে "+base+"টি পণ্য প্রতিটি "+b+" টাকায় বিক্রি হলে মোট বিক্রয় কত টাকা?";
      correct=base*b;
      why="মোট বিক্রয় = সংখ্যা × একক মূল্য = "+correct+"।";
      break;
    case "population":
      q="এক অঞ্চলের আয়তন "+b+" বর্গকিমি ও জনসংখ্যা "+(base*b)+" হলে প্রতি বর্গকিমিতে জনঘনত্ব কত?";
      correct=base;
      why="ঘনত্ব = জনসংখ্যা ÷ আয়তন = "+(base*b)+"÷"+b+" = "+correct+"।";
      break;
    default:throw Error("Unknown template "+kind);
  }
  const offsets=[b+3,b+c+9,b+2*c+17];
  const options=[correct,correct+offsets[0],correct+offsets[1],correct-offsets[2]].map(String);
  if(new Set(options).size!==4)throw Error("Duplicate math choice "+kind);
  const answer=(index+kind.length)%4,remaining=options.slice(1);
  remaining.splice(answer,0,options[0]);
  return {id:"worked-"+level+"-"+subject+"-"+kind+"-"+index,grade:Number(level)||null,subject,q,
    options:remaining,answer,why,generated:true,topic:kind};
}
