function stableChoice(correct,wrong,number){
  const answers=[String(correct),...wrong.map(String)];
  if(new Set(answers).size!==4)throw Error("Repeated answer choices");
  const answer=number%4;
  const options=answers.slice(1);
  options.splice(answer,0,answers[0]);
  return {options,answer};
}
export function createConceptQuestions(stream,level) {
  if(!FACTS[stream])return [];
  return FACTS[stream].map(([subject,q,correct,wrong,why],i)=>({
    id:"concept-"+stream+"-"+i,grade:Number(level)||null,stream,subject,q,why,
    ...stableChoice(correct,wrong,i+Number(level||0))
  }));
}
