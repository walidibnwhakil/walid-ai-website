function makePrimaryMath(grade, index) {
  const a = 8 + index + grade * 3;
  const b = 2 + index % (grade < 3 ? 9 : 13);
  const kind = index % 5;
  let q, answer, why;
  if (grade <= 2) {
    if (kind === 0) { q = a + " + " + b + " = কত?"; answer = a + b; why = "সংখ্যা দুটি যোগ করলে " + answer + "।"; }
    else if (kind === 1) { q = (a + b) + " − " + b + " = কত?"; answer = a; why = "বিয়োগ করলে " + a + " থাকে।"; }
    else if (kind === 2) { q = a + " থেকে " + (a - b) + " বিয়োগ করলে কত থাকে?"; answer = b; why = a + " − " + (a-b) + " = " + b + "।"; }
    else if (kind === 3) { q = a + " + □ = " + (a+b) + " হলে □ কত?"; answer = b; why = (a+b) + " − " + a + " = " + b + "।"; }
    else { q = a + "টি ফলের সঙ্গে " + b + "টি ফল যোগ হলে মোট কয়টি?"; answer = a+b; why = a + " + " + b + " = " + answer + "।"; }
  } else if (grade === 3) {
    if (kind === 0) { q = a + " × " + b + " = কত?"; answer = a*b; why = a + " কে " + b + " বার যোগ করলে " + answer + "।"; }
    else if (kind === 1) { q = (a*b) + " ÷ " + b + " = কত?"; answer = a; why = b + " × " + a + " = " + a*b + "।"; }
    else if (kind === 2) { q = a + " + " + b + " × 2 = কত?"; answer = a+2*b; why = "আগে গুণ: " + b + "×2=" + 2*b + "; পরে যোগ = " + answer + "।"; }
    else if (kind === 3) { q = "একটি বাক্সে " + a + "টি কলম। " + b + "টি বাক্সে মোট কতটি?"; answer = a*b; why = a + " × " + b + " = " + answer + "।"; }
    else { q = a + " এবং " + (a+2*b) + " এর মধ্যবর্তী গড় কত?"; answer = a+b; why = "দুটি সংখ্যার যোগফলের অর্ধেক = " + answer + "।"; }
  } else if (grade === 4) {
    if (kind === 0) { q = a + " × " + b + " = কত?"; answer = a*b; why = "গুণফল " + answer + "।"; }
    else if (kind === 1) { q = (a*b) + " ÷ " + b + " = কত?"; answer = a; why = "ভাগফল " + answer + "।"; }
    else if (kind === 2) { q = "একটি আয়তক্ষেত্রের দৈর্ঘ্য " + a + " এবং প্রস্থ " + b + " হলে ক্ষেত্রফল কত?"; answer = a*b; why = "ক্ষেত্রফল = দৈর্ঘ্য × প্রস্থ = " + answer + "।"; }
    else if (kind === 3) { q = a + " + " + b + " × 3 = কত?"; answer = a+3*b; why = "আগে গুণ, পরে যোগ = " + answer + "।"; }
    else { q = "সমান " + b + " ভাগে " + a*b + "টি ফল ভাগ করলে প্রত্যেকে কয়টি পায়?"; answer = a; why = a*b + " ÷ " + b + " = " + answer + "।"; }
  } else {
    if (kind === 0) { q = "একটি আয়তক্ষেত্রের দৈর্ঘ্য " + a + " মি ও প্রস্থ " + b + " মি হলে পরিসীমা কত?"; answer = 2*(a+b); why = "২ × (দৈর্ঘ্য + প্রস্থ) = " + answer + " মি।"; }
    else if (kind === 1) { q = a + " × " + b + " = কত?"; answer = a*b; why = "গুণফল = " + answer + "।"; }
    else if (kind === 2) { q = "মোট " + (a*b) + " টাকা " + b + " জনে সমান ভাগ করলে প্রত্যেকে কত টাকা পায়?"; answer = a; why = "মোট টাকা ÷ মানুষের সংখ্যা = " + answer + "।"; }
    else if (kind === 3) { q = "x + " + b + " = " + (a+b) + " হলে x কত?"; answer = a; why = "উভয় পাশ থেকে " + b + " বিয়োগ করলে x=" + a + "।"; }
    else { q = "একটি বর্গের বাহু " + a + " মি হলে ক্ষেত্রফল কত বর্গমিটার?"; answer = a*a; why = "বর্গের ক্ষেত্রফল = বাহু × বাহু = " + a*a + "।"; }
  }
  return build("p-"+grade+"-math-"+index,grade,"গণিত",q,answer,[answer+b,answer-b,answer+2*b],why,index);
}
export function createPrimaryBank(grade) {
  if (!Number.isInteger(grade)||grade<1||grade>5) throw Error("Primary grade must be 1–5");
  const items=[];
  for(let i=0;i<100;i++) items.push(makePrimaryMath(grade,i));
  const bengali=grade<=2?firstLetters:advancedBangla;
  bengali.forEach(([word,correct],i)=>{
    const isLetter=grade<=2;
    const alternatives=(isLetter
      ? [...new Set(firstLetters.map(x=>x[1]))]
      : advancedBangla.map(x=>x[1])).filter(x=>x!==correct);
    const wrong=[0,1,2].map(k=>alternatives[(i*3+k)%alternatives.length]);
    items.push(build("p-"+grade+"-bn-"+i,grade,"বাংলা",
      isLetter?"‘"+word+"’ শব্দের প্রথম বর্ণ কোনটি?":"‘"+word+"’ শব্দের কাছাকাছি অর্থ কোনটি?",
      correct,wrong,(isLetter?"‘"+word+"’ শব্দের প্রথম বর্ণ ":"‘"+word+"’ শব্দের অর্থ ")+"‘"+correct+"’।",i));
  });
  const english=grade<=2?englishEasy:englishHigher;
  english.forEach(([word,correct],i)=>{
    const alternatives=english.map(x=>x[1]).filter(x=>x!==correct);
    const wrong=[0,1,2].map(k=>alternatives[(i*3+k)%alternatives.length]);
    items.push(build("p-"+grade+"-en-"+i,grade,"ইংরেজি",
      "‘"+word+"’ শব্দের বাংলা অর্থ কী?",correct,wrong,
      "‘"+word+"’ শব্দের বাংলা অর্থ ‘"+correct+"’।",i+1));
  });
  const environment=grade<=2?environmentEasy:environmentHigher;
  environment.forEach(([q,correct,wrong,why],i)=>{
    items.push(build("p-"+grade+"-env-"+i,grade,grade<=2?"পরিবেশ ও জীবন":"প্রাথমিক বিজ্ঞান ও সমাজ",q,correct,wrong,why,i+2));
  });
  return items;
}

