export function createExamExtras() {
  return examItems.map(([subject,q,correct,wrong,why],i) =>
    build("bcs-extra-"+i,"bcs",subject,q,correct,wrong,why,i));
}

export function auditQuestion(question) {
  return Boolean(question && question.id!=null && question.q?.trim() &&
    question.subject?.trim() && Array.isArray(question.options) &&
    question.options.length===4 && new Set(question.options.map(String)).size===4 &&
    Number.isInteger(question.answer) && question.answer>=0 && question.answer<4 &&
    question.why?.trim());
}
