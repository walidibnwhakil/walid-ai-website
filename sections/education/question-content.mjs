const answers = (correct, wrong, offset = 0) => {
  const unique = [String(correct), ...wrong.map(String)].filter((x, i, a) => a.indexOf(x) === i);
  if (unique.length !== 4) throw Error("Invalid question choices");
  const slot = offset % 4;
  const shuffled = unique.slice(1);
  shuffled.splice(slot, 0, unique[0]);
  return {options: shuffled, answer: slot};
};
